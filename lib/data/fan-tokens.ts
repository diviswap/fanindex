// Helper function to get tokens by category
export function getTokensByCategory(category: FanToken["category"]): FanToken[] {
  return FAN_TOKENS.filter((token) => token.category === category)
}

// Helper function to get top tokens by market cap
export function getTopTokens(limit = 10): FanToken[] {
  return FAN_TOKENS.slice(0, limit)
}

// Helper function to get token by symbol
export function getTokenBySymbol(symbol: string): FanToken | undefined {
  return FAN_TOKENS.find((token) => token.symbol === symbol)
}

export function getTokenByAddress(address: string): FanToken | undefined {
  const lowerAddress = address.toLowerCase()
  return FAN_TOKENS.find(
    (token) => token.wrapped?.toLowerCase() === lowerAddress || token.unwrapped?.toLowerCase() === lowerAddress,
  )
}
